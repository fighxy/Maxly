import Foundation

/// До какого места чат прочитан этим аккаунтом (мс, серверное время сообщения).
///
/// Берётся самая свежая из трёх отметок:
/// - `card` — своя отметка, которую хранит сервер (на iOS — ответ сервера на свою отметку:
///   карточка чата в мосте ядра своей отметки не несёт);
/// - `pushed` — своя отметка из пуша прочтения (с другого устройства);
/// - `local` — отметка, до которой чат прочитан только на этом устройстве, пока отметки о
///   прочтении не отправляются (`GhostControls.localReadMark`).
///
/// Без местной разделитель непрочитанных каждый раз возвращался бы к отметке сервера, которая
/// при скрытых отметках не двигается. `0` — отметки нет.
public enum OwnReadMark {
    public static func position(card: Int64, pushed: Int64, local: Int64) -> Int64 {
        max(0, card, pushed, local)
    }
}
